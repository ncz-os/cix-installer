#!/bin/bash
# 80-npu.sh — install NCZ NPU stack for Cix Sky1 / Zhouyi v3
#
# Source: FyrbyAdditive/ms-r1-npu-hack (BSD-2-Clause-Patent)
#   + cixtech/cix_opensource__release__npu_driver branch cix_mainline_dev
#
# Four MS-R1 fixes applied in the kernel module:
#   1. ACPI SSDT override: _HID="CIXH4010" on NPU cores (missing in shipped BIOS)
#   2. v0-compat ioctl handlers: translates cix-noe-umd 2.0.x struct layouts
#   3. SMMU 32-bit constraint: forces bus_dma_limit=0xc0000000, dma_mask=32
#   4. asid_base[4]->asid_base[32] widening for QUERY_CAP UMD ABI compat
#
# Result: mobilenet_v2.cix runs at ~640 inf/s (1.5ms avg) via cix-noe-umd 2.0.2
#
# RUNS INSIDE CHROOT (via run-all.sh). All paths are relative to the
# installed system root (no /target/ prefix).
#
# Ordering: this hook runs before 70-bootloader.sh (which fires on EXIT trap).
# Sequence:
#   1. install .ko into /usr/lib/modules/$KVER/extra/
#   2. depmod -a $KVER
#   3. ensure /boot/initrd.img-$KVER exists (normally generated by 10-our-kernel.sh)
#   4. prepend npu-acpi-override.cpio to /boot/initrd.img-$KVER
#   5. configure modules-load.d
# Then 70-bootloader.sh stages /boot/initrd.img-$KVER → /boot/efi/initrd.img-$KVER
# and adds `initrd /initrd.img-$KVER` to the rEFInd boot entries.

# NCZ-PLATFORM-GUARD: sky1-arm64 only (docs/PLATFORM-SPLIT-DESIGN.md). Arch order matches
# run-all.sh: NCZ_TARGET_ARCH, then the late.sh BUILD_ARCH stamp, then dpkg. An
# undetectable arch does NOT skip (legacy behavior).
_ncz_pg_arch="${NCZ_TARGET_ARCH:-}"
[ -n "$_ncz_pg_arch" ] || _ncz_pg_arch=$(cat /usr/local/lib/cix-installer/BUILD_ARCH 2>/dev/null | tr -d '[:space:]')
[ -n "$_ncz_pg_arch" ] || _ncz_pg_arch=$(dpkg --print-architecture 2>/dev/null || true)
case "$_ncz_pg_arch" in
    arm64|aarch64|"") ;;
    *) echo "[${0##*/}] platform guard: arch=$_ncz_pg_arch is not sky1-arm64; skipping"; exit 0 ;;
esac
unset _ncz_pg_arch
set +e

# Zhouyi v3 NPU is Sky1/arm64-only hardware. Without this guard, run-all.sh
# runs this hook unconditionally on every image including amd64 T2 builds --
# same class of bug fixed 2026-09-22 in 83-panthor-gpu.sh after it broke a
# real amd64 kernel install (registered arm64-only DKMS source that fails to
# compile on x86_64). Match the arch-guard convention from 54-gpu-accel.sh /
# 55-t2-firmware.sh / 83-panthor-gpu.sh.
if [ "$(dpkg --print-architecture 2>/dev/null)" != "arm64" ]; then
    echo "[80] not arm64 (Sky1 NPU hardware only) -- skipping"
    exit 0
fi

INSTALLER_META=/usr/local/lib/cix-installer
ASSETS=/usr/local/lib/cix-installer/assets/npu
if [ ! -d "$ASSETS" ] && [ -d /cdrom/ncz-payload/assets/npu ]; then
    ASSETS=/cdrom/ncz-payload/assets/npu
fi
SSDT_CPIO="$ASSETS/npu-acpi-override.cpio"

# Kernels to act on (post-install/lib/sky1-kernels.sh): the KVER_NEXT sidecar
# is authoritative and, on a normal install, names the one shipped kernel
# (assets/kernel/mainline -> KVER_NEXT, 7.3.0-rc7-sky1-ncz for 26.10). Any
# other NCZ Sky1 kernel module tree on disk (*-sky1-ncz) that the sidecar
# does not name -- a kernel package installed by hand, or sidecar drift -- is
# folded in too: without it that kernel's initrd would miss the CIXH4010 _HID
# overlay and the NPU cores would hard-hang on first register read. Every
# per-kernel step below tolerates a kernel without an NPU module (it warns and
# moves on), and the SSDT prepend checks the newc magic first, so this is
# idempotent. Without the helper (an older medium) only the sidecar is used.
KERNEL_LABELS=()
KERNEL_VERS=()
HERE="$(dirname "$0")"
if [ -r "$HERE/lib/sky1-kernels.sh" ]; then
    # shellcheck source=lib/sky1-kernels.sh
    . "$HERE/lib/sky1-kernels.sh"
    _kernels=$(ncz_sky1_kernel_vers "$INSTALLER_META")
else
    _kernels=""
    if [ -f "$INSTALLER_META/KVER_NEXT" ]; then
        _kv=$(tr -d ' \t\r\n' < "$INSTALLER_META/KVER_NEXT" 2>/dev/null)
        [ -n "$_kv" ] && _kernels="sidecar $_kv"
    fi
fi
while read -r _src _kv; do
    [ -n "$_kv" ] || continue
    if [ "$_src" = disk ]; then
        echo "[80] NCZ Sky1 kernel $_kv present but not in KVER_NEXT sidecar — folding in for NPU SSDT"
    fi
    KERNEL_LABELS+=("mainline")
    KERNEL_VERS+=("$_kv")
done <<< "$_kernels"
unset _kernels _src _kv

if [ "${#KERNEL_VERS[@]}" -eq 0 ]; then
    echo "[80] WARN: no Sky1 kernel found (no KVER_NEXT sidecar, no *-sky1-ncz module tree); skipping kernel-specific NPU setup"
fi
if [ ! -d "$ASSETS" ]; then
    # assets/npu/ is a gitignored blob dir carrying two OPTIONAL payloads: the
    # out-of-tree armchina_npu-<KVER>.ko (only needed when the kernel does not
    # build the driver in-tree) and the MS-R1 ACPI SSDT override. Both are
    # board/kernel-specific, so an absent directory is not automatically a
    # problem — say what is actually being skipped instead of a bare WARN.
    echo "[80] NPU asset directory not staged at $ASSETS"
    echo "[80]   -> no out-of-tree armchina_npu-<KVER>.ko (fine if the kernel ships it in-tree)"
    echo "[80]   -> no MS-R1 ACPI SSDT override (fine on boards with a native CIXH4010 _HID)"
fi

echo "[80] installing NCZ NPU stack (FyrbyAdditive MS-R1 fixes)..."

# --- Step 1: install kernel modules ---
# Two supported sources, in priority order:
#   1. In-tree module shipped inside modules-cixmini.tgz, when the kernel was
#      built with CONFIG_ARMCHINA_NPU=m: it already carries the correct
#      vermagic. Nothing to copy — just confirm + depmod.
#   2. Out-of-tree prebuilt $ASSETS/armchina_npu-${KVER}.ko, whose vermagic MUST
#      exactly match $KVER, for a kernel whose config does NOT enable it.
#   The shipping 7.3 defconfig leaves CONFIG_ARMCHINA_NPU unset; the NPU driver
#   actually loaded is the vendor aipu.ko built by DKMS (see the end of this hook).
for i in "${!KERNEL_VERS[@]}"; do
    LABEL="${KERNEL_LABELS[$i]}"
    KVER="${KERNEL_VERS[$i]}"
    if [ ! -d "/usr/lib/modules/$KVER" ]; then
        echo "[80] WARN: /usr/lib/modules/$KVER does not exist; skipping $KVER"
        continue
    fi

    INTREE=$(find "/usr/lib/modules/$KVER/kernel" -name 'armchina_npu.ko*' 2>/dev/null | head -1)
    SRC="$ASSETS/armchina_npu-${KVER}.ko"

    if [ -n "$INTREE" ]; then
        # In-tree build: driver already present with matching vermagic.
        depmod -a "$KVER" 2>/dev/null
        echo "[80] $LABEL/$KVER: using in-tree armchina_npu.ko ($INTREE)"
    elif [ -f "$SRC" ]; then
        # Guard: refuse to install a vermagic-mismatched OOT module — loading it
        # would either be rejected by modprobe or (with MODVERSIONS off) risk a
        # silent ABI mismatch. Skip loudly instead.
        VM=$(modinfo -F vermagic "$SRC" 2>/dev/null | awk '{print $1}')
        if [ -n "$VM" ] && [ "$VM" != "$KVER" ]; then
            echo "[80] ERROR: $SRC vermagic '$VM' != kernel '$KVER'; refusing to install (rebuild OOT module for $KVER)"
            continue
        fi
        install -D -m 0644 "$SRC" "/usr/lib/modules/$KVER/extra/armchina_npu.ko"
        depmod -a "$KVER" 2>/dev/null
        echo "[80] $LABEL/$KVER: installed OOT armchina_npu.ko (vermagic $VM)"
    else
        echo "[80] WARN: no in-tree module and no $SRC; NPU unavailable for $LABEL/$KVER"
    fi

    # --- Overlay override (NCZ validated fixes, r104) ---
    # The in-tree armchina_npu.ko in modules-cixmini.tgz may predate the
    # ARCH_V3=y + iova_region=2 fixes (Zhouyi V3 detection / 32-bit-bus IOVA
    # cap). A validated overlay installed to updates/ takes depmod precedence
    # over kernel/, so the correct module loads even on an unrebuilt kernel.
    OVERLAY=""
    for cand in \
        "/usr/local/lib/cix-installer/assets/kernel/modules-overlay/$KVER/armchina_npu.ko" \
        "/cdrom/ncz-payload/assets/kernel/modules-overlay/$KVER/armchina_npu.ko"; do
        [ -f "$cand" ] && { OVERLAY="$cand"; break; }
    done
    if [ -n "$OVERLAY" ]; then
        OVM=$(modinfo -F vermagic "$OVERLAY" 2>/dev/null | awk '{print $1}')
        if [ -n "$OVM" ] && [ "$OVM" != "$KVER" ]; then
            echo "[80] WARN: overlay $OVERLAY vermagic '$OVM' != '$KVER'; not applying"
        else
            install -D -m 0644 "$OVERLAY" "/usr/lib/modules/$KVER/updates/armchina_npu.ko"
            depmod -a "$KVER" 2>/dev/null
            echo "[80] $LABEL/$KVER: applied validated NPU overlay (ARCH_V3+iova=2, vermagic $OVM) -> updates/"
        fi
    fi
done

# --- Step 1b: ensure the matched aipu DKMS module (cix-npu-driver-dkms, installed
# by 25-cix-proprietary.sh) is built for each TARGET kernel. dpkg's dkms postinst
# runs `dkms autoinstall` over /lib/modules/*/build dirs; be explicit per target
# KVER so an in-target install (chroot uname != target KVER) still yields
# /usr/lib/modules/$KVER/updates/dkms/aipu.ko. Idempotent; leaves the SSDT +
# power/control=auto lifecycle to the driver (never force power on). ---
if command -v dkms >/dev/null 2>&1 && dkms status 2>/dev/null | grep -qE '^aipu[,/]'; then
    AIPU_VER=$(dkms status 2>/dev/null | sed -n 's#^aipu[,/] *\([0-9][0-9.]*\).*#\1#p' | head -1)
    for KVER in "${KERNEL_VERS[@]}"; do
        [ -d "/usr/lib/modules/$KVER" ] || continue
        if ls /usr/lib/modules/$KVER/updates/dkms/aipu.ko* >/dev/null 2>&1; then
            echo "[80] aipu dkms already built for $KVER"
        elif [ -d "/usr/lib/modules/$KVER/build" ]; then
            echo "[80] building aipu dkms ${AIPU_VER:-6.2.0} for $KVER..."
            dkms install -m aipu -v "${AIPU_VER:-6.2.0}" -k "$KVER" --force 2>&1 | tail -4 || echo "[80] WARN: aipu dkms build failed for $KVER"
            depmod -a "$KVER" 2>/dev/null
        else
            echo "[80] WARN: no headers at /usr/lib/modules/$KVER/build - cannot build aipu dkms for $KVER"
        fi
    done
fi

# --- Step 2: ensure initrd exists for each NCZ kernel ---
# 10-our-kernel.sh now generates initrds in the required phase. Keep this
# fallback for older/rerun targets, but the boot-critical path no longer
# depends on this optional hook.
for KVER in "${KERNEL_VERS[@]}"; do
    if [ -d "/usr/lib/modules/$KVER" ]; then
        if [ ! -f "/boot/initrd.img-$KVER" ]; then
            echo "[80] generating initrd for $KVER..."
            update-initramfs -c -k "$KVER" 2>&1 | tail -5
        else
            echo "[80] initrd already present for $KVER"
        fi
    fi
done

# --- Step 3: ACPI SSDT override — DELIVERED BY THE INITRAMFS BUILDER ---
#
# The SSDT injects _HID="CIXH4010" onto the NPU compute cores (CRE0/CRE1/CRE2).
# This is a fix for ONE specific defect: the Minisforum MS-R1's shipped BIOS
# omits that _HID, so the cores never enumerate (CIXH4000:00 appears but no
# CIXH4010:0x), and aipu logs
#     "only 0 of 3 NPU cores usable - disabling NPU"
#
# THE CANONICAL MECHANISM
# -----------------------
# The kernel's CONFIG_ACPI_TABLE_UPGRADE (verified =y in the r290 config, see
# TASK notes and build/test-npu-ssdt-delivery.sh) instaloads any
# kernel/firmware/acpi/*.aml it finds in an UNCOMPRESSED CPIO archive stacked
# in front of (or inside the root of) the initramfs. So the override has to be
# produced BY the initramfs generator, on every regeneration:
#
#   dracut (this image's builder, see post-install/94-dracut-config.sh):
#       /usr/lib/dracut/modules.d/91ncz-npu-ssdt/module-setup.sh
#   initramfs-tools (fallback builder):
#       /etc/initramfs-tools/hooks/ncz-npu-ssdt
#         + /etc/initramfs-tools/post-update.d/zz-ncz-npu-ssdt (belt + braces)
#
# Both hook modules are BOARD-GATED by the same shared decision helper
# (post-install/lib/npu-ssdt.sh, ncz_npu_ssdt_decision), which is the DMI gate
# modelled on ncz_efi_rt_workaround(): known-good boards are checked first and
# always win, so Radxa Orion O6/O6N never receive an SSDT that would collide
# with the _HID their firmware already provides.
#
# WHAT THIS HOOK DOES — AND DOES NOT — HAVE TO DO
# -----------------------------------------------
# THIS hook (install time) does three things:
#   1. stage the compiled .aml so the builder on the installed system can use
#      it:  $META/assets/npu/ssdt-npucre.aml
#        (the sources live in the gitignored assets/npu/ blob dir; only
#         ssdt-npucre.asl is committed and build/build-npu-ssdt.sh compiles it
#         with iasl at build time — no binary is ever committed)
#   2. install the dracut module and/or the initramfs-tools hooks on the target
#   3. force one initrd rebuild so the CURRENT image boots with the override,
#      instead of waiting for the next kernel upgrade to deliver it.
# It no longer cat's a pre-built blob in front of /boot/initrd.img-*: that was
# the previous approach and it is what silently failed, because
#    - update-initramfs/dracut REGENERATE the file from scratch, dropping the
#      prepend, and
#    - post-update.d is an initramfs-tools path, and this image uses dracut,
#      so the "survives regeneration" hook never ran at all.
#
# Detection priority (runs in the d-i chroot, where /proc /sys /dev are
# bind-mounted, so it reflects the REAL hardware being installed):
#   0. operator override  /usr/local/lib/cix-installer/NPU_SSDT = force|skip
#   1. functional ACPI check (authoritative, board-agnostic):
#        >=3 CIXH4010:* cores present -> enumerate natively   -> SKIP
#        CIXH4000:00 present, <3 cores -> MS-R1-class bug      -> APPLY
#   2. DMI board match (only if ACPI gives no signal):
#        MS-R1 / "Micro Computer (HK)" -> APPLY ; Radxa / Orion -> SKIP
#   3. unknown + no CIX NPU ACPI signal -> SKIP + warn (refuse to inject an
#        MS-R1 SSDT into unidentified hardware).
#
# The shared helper is the single source of truth for this decision; the
# function below is kept as a thin, name-stable wrapper so existing callers and
# tests keep working.
NPU_SSDT_LIB="$HERE/lib/npu-ssdt.sh"
if [ -r "$NPU_SSDT_LIB" ]; then
    # shellcheck source=lib/npu-ssdt.sh
    . "$NPU_SSDT_LIB"
fi

should_apply_npu_ssdt() {
    if [ -r "$NPU_SSDT_LIB" ]; then
        [ "$(ncz_npu_ssdt_decision "$INSTALLER_META")" = "apply" ]
        return $?
    fi

    # Fallback: the helper was not staged (older medium). Same rules, minus
    # the ACPI cross-check, with the DMI gate still in force.
    local force="$INSTALLER_META/NPU_SSDT"
    if [ -f "$force" ]; then
        case "$(tr -d ' \t\r\n' < "$force" 2>/dev/null)" in
            force|apply|on|1) echo "[80] NPU SSDT: forced ON by $force"; return 0 ;;
            skip|off|0)       echo "[80] NPU SSDT: forced OFF by $force"; return 1 ;;
        esac
    fi
    local pn pf sv
    pn=$(cat /sys/class/dmi/id/product_name   2>/dev/null)
    pf=$(cat /sys/class/dmi/id/product_family 2>/dev/null)
    sv=$(cat /sys/class/dmi/id/sys_vendor     2>/dev/null)
    case "$pn" in
        *"Orion O6"*|*"Orange Pi 6"*|*"OrangePi 6"*) return 1 ;;
    esac
    case "$sv" in
        *Radxa*|*Xunlong*) return 1 ;;
    esac
    case "$pn $pf" in
        *MS-R1*) return 0 ;;
    esac
    case "$sv" in
        *"Micro Computer (HK)"*) return 0 ;;
    esac
    echo "[80] NPU SSDT: board UNKNOWN (pn='$pn' pf='$pf' sv='$sv') — SKIP (refusing to inject MS-R1 SSDT into unidentified hardware)"
    echo "[80]   (force on a known MS-R1-class board with: echo force > $INSTALLER_META/NPU_SSDT)"
    return 1
}

# Path to the builder modules exactly as the image stages them under $META.
NPU_DRACUT_SRC=""
NPU_INITRAMFS_SRC=""
for _cand in "$INSTALLER_META/assets" "/cdrom/ncz-payload/assets"; do
    [ -d "$_cand/dracut/modules.d/91ncz-npu-ssdt" ] && NPU_DRACUT_SRC="$_cand/dracut/modules.d/91ncz-npu-ssdt"
    [ -d "$_cand/initramfs/hooks" ] && NPU_INITRAMFS_SRC="$_cand/initramfs"
    [ -n "$NPU_DRACUT_SRC$NPU_INITRAMFS_SRC" ] && break
done

# Set when the override was REQUIRED by the board decision but could not be
# proven to be inside the initrd. Returned as the hook's exit status: on arm64
# run-all.sh treats 80-npu as a critical hook, so an MS-R1 that would boot with
# a dead NPU fails the install instead of shipping. (Two releases went out with
# "only 0 of 3 NPU cores usable - disabling NPU" because this was a warning.)
NPU_SSDT_DELIVERY_FAILED=0

# npu_ssdt_verify_initrd <initrd> — the kernel's CONFIG_ACPI_TABLE_UPGRADE
# loader only reads an UNCOMPRESSED newc archive physically prepended in front
# of the compressed image, and the entry name must be exactly
# kernel/firmware/acpi/ssdt-npucre.aml. Both properties are visible in the
# first bytes of the file, so this needs no unpacking.
npu_ssdt_verify_initrd() {
    [ -s "$1" ] || return 1
    [ "$(head -c 6 "$1" 2>/dev/null)" = "070701" ] || return 1
    head -c 4096 "$1" 2>/dev/null | grep -qa 'kernel/firmware/acpi/ssdt-npucre.aml' || return 1
    return 0
}

if should_apply_npu_ssdt; then
    # 3.1 — the .aml the target-side builder consumes.
    if [ -s "$ASSETS/ssdt-npucre.aml" ]; then
        echo "[80] NPU SSDT: compiled table staged at $ASSETS/ssdt-npucre.aml"
    else
        # 2026-10-28: this used to be a WARN, and that is precisely how the
        # MS-R1 shipped twice with a disabled NPU: the build never compiled
        # the table (nothing called build-npu-ssdt.sh), the hook installed
        # correctly, and there was simply nothing to inject. The build-side
        # fix is build/iso/ncz_ssdt.py (called by write-usb-image.py). If the
        # table is still absent here the medium is defective; say so and fail.
        echo "[80] ERROR: $ASSETS/ssdt-npucre.aml missing on a board that NEEDS it."
        echo "[80]        The NPU cores have no _HID without this table, so the"
        echo "[80]        NPU would boot disabled. The build is defective:"
        echo "[80]        build/iso/ncz_ssdt.py must stage it into assets/npu/."
        NPU_SSDT_DELIVERY_FAILED=1
    fi

    # 3.2 — install the initramfs-tools hook + post-update hook.
    if [ -n "$NPU_INITRAMFS_SRC" ]; then
        install -d -m 0755 /etc/initramfs-tools/hooks /etc/initramfs-tools/post-update.d
        install -m 0755 "$NPU_INITRAMFS_SRC/hooks/ncz-npu-ssdt" \
            /etc/initramfs-tools/hooks/ncz-npu-ssdt
        install -m 0755 "$NPU_INITRAMFS_SRC/post-update.d/zz-ncz-npu-ssdt" \
            /etc/initramfs-tools/post-update.d/zz-ncz-npu-ssdt
        echo "[80] installed initramfs-tools hooks ncz-npu-ssdt (stages kernel/firmware/acpi/ssdt-npucre.aml)"
    else
        echo "[80] WARN: initramfs-tools hook sources not staged — dracut path only"
    fi

    # 3.3 — install the dracut module (the builder this image actually uses).
    if [ -n "$NPU_DRACUT_SRC" ]; then
        install -d -m 0755 /usr/lib/dracut/modules.d
        rm -rf /usr/lib/dracut/modules.d/91ncz-npu-ssdt
        cp -a "$NPU_DRACUT_SRC" /usr/lib/dracut/modules.d/91ncz-npu-ssdt
        chmod 0755 /usr/lib/dracut/modules.d/91ncz-npu-ssdt/module-setup.sh
        echo "[80] installed dracut module 91ncz-npu-ssdt (builds the early CPIO on every rebuild)"
    else
        echo "[80] WARN: dracut module sources not staged — initramfs-tools path only"
    fi

    # 3.4 — keep a copy of the early CPIO at /boot for the post-update safety
    # net and for operator inspection. It is NOT the delivery mechanism: the
    # builders regenerate the table from the staged .aml each time.
    if [ -r "$NPU_SSDT_LIB" ] && [ -s "$ASSETS/ssdt-npucre.aml" ]; then
        if ncz_npu_ssdt_build_early_cpio /boot/npu-acpi-override.cpio "$INSTALLER_META" >/dev/null 2>&1; then
            echo "[80] early CPIO available at /boot/npu-acpi-override.cpio (fallback only)"
        else
            echo "[80] WARN: could not build the /boot early CPIO (fallback unavailable)"
        fi
    fi

    # 3.5 — rebuild each initrd NOW so this install boots with the override.
    # The module/hook does the work; if the rebuild does not pick it up the
    # problem is in the builder, and saying so here is the only chance to.
    #
    # VERIFIED ON REAL HARDWARE (MS-R1/cixmini, 2026-10-18): the dracut module's
    # own staged payload (usr/share/ncz/acpi*) lands inert inside the normal
    # COMPRESSED initramfs. Nothing in this tree sets dracut's native
    # acpi_override=yes/acpi_table_dir= knobs, so dracut never builds the
    # separate UNCOMPRESSED early-CPIO segment the kernel's
    # CONFIG_ACPI_TABLE_UPGRADE loader actually scans (it only reads an
    # uncompressed cpio physically prepended before the compressed image —
    # confirmed via `od -c`: a freshly dracut-built $INITRD starts with the
    # zstd magic, not cpio's 070701). Without the unconditional prepend below,
    # /sys/bus/acpi/devices/CIXH4010:* and /dev/aipu never appear, even though
    # every unit test in build/test-npu-ssdt-delivery.sh passes (they test the
    # standalone artifact, not the final assembled initrd). The prepend is
    # safe to run every time: dracut --force / update-initramfs -u always
    # rebuild $INITRD from scratch, so this never double-prepends.
    for KVER in "${KERNEL_VERS[@]}"; do
        [ -d "/usr/lib/modules/$KVER" ] || continue
        INITRD="/boot/initrd.img-$KVER"
        [ -f "$INITRD" ] || { echo "[80] WARN: no $INITRD to rebuild for $KVER"; continue; }
        _ncz_rebuilt=0
        if command -v dracut >/dev/null 2>&1; then
            if dracut --force --kver "$KVER" "$INITRD" >/dev/null 2>&1; then
                echo "[80] rebuilt $INITRD with dracut (91ncz-npu-ssdt active)"
                _ncz_rebuilt=1
            else
                echo "[80] WARN: dracut failed to rebuild $INITRD; NPU SSDT may be absent"
            fi
        elif command -v update-initramfs >/dev/null 2>&1; then
            if update-initramfs -u -k "$KVER" >/dev/null 2>&1; then
                echo "[80] rebuilt $INITRD with update-initramfs (ncz-npu-ssdt hook active)"
                _ncz_rebuilt=1
            else
                echo "[80] WARN: update-initramfs failed for $KVER; NPU SSDT may be absent"
            fi
        fi
        # Step 3.4 just (re)built /boot/npu-acpi-override.cpio fresh from the
        # currently-staged .aml; prefer it over the build-time-baked
        # $SSDT_CPIO ($ASSETS/npu-acpi-override.cpio) so a changed asset on
        # this install is reflected even if the baked copy is stale.
        _ncz_early_cpio=/boot/npu-acpi-override.cpio
        [ -s "$_ncz_early_cpio" ] || _ncz_early_cpio="$SSDT_CPIO"
        if [ "$_ncz_rebuilt" = 1 ] && [ -s "$_ncz_early_cpio" ]; then
            if cat "$_ncz_early_cpio" "$INITRD" > "$INITRD.ncz-tmp" && mv "$INITRD.ncz-tmp" "$INITRD"; then
                echo "[80] prepended NPU SSDT early-CPIO onto $INITRD (CIXH4010 cores will enumerate)"
            else
                rm -f "$INITRD.ncz-tmp"
                echo "[80] ERROR: could not prepend NPU SSDT early-CPIO onto $INITRD"
                NPU_SSDT_DELIVERY_FAILED=1
            fi
        elif [ "$_ncz_rebuilt" = 1 ]; then
            echo "[80] ERROR: no early CPIO to prepend (neither /boot/npu-acpi-override.cpio nor $SSDT_CPIO)"
            NPU_SSDT_DELIVERY_FAILED=1
        fi
        # VERIFY THE RESULT, do not trust the steps above. This is the check
        # that was missing: every individual step "succeeded" on the 2026-10-28
        # MS-R1 image while the initrd contained zero kernel/firmware/acpi
        # entries, because the .aml was never staged.
        if ! npu_ssdt_verify_initrd "$INITRD"; then
            echo "[80] ERROR: $INITRD does not carry the NPU SSDT early-CPIO"
            echo "[80]        (expected an uncompressed 070701 archive naming"
            echo "[80]        kernel/firmware/acpi/ssdt-npucre.aml at the front)"
            NPU_SSDT_DELIVERY_FAILED=1
        else
            echo "[80] verified: $INITRD early-CPIO carries ssdt-npucre.aml"
        fi
    done
elif [ -s "$ASSETS/ssdt-npucre.aml" ] || [ -f "$SSDT_CPIO" ]; then
    # 2026-08-02: this used to warn unconditionally, which produced a scary
    # "NPU cores may not enumerate" line on every O6/O6N install even though
    # the detector would have skipped the override on those boards anyway
    # (their firmware exposes the CIXH4010 _HID natively). Ask the detector
    # first, so the message only fires on a board that actually needed it.
    echo "[80] NPU SSDT override staged but NOT applied for this board (see detection above)"
else
    echo "[80] NPU SSDT assets not staged — not needed on this board (native _HID)"
fi


# --- Step 4: auto-load on boot ---
mkdir -p /etc/modules-load.d
cat > /etc/modules-load.d/ncz-npu.conf << 'EOF'
# NCZ 26.6: Cix Sky1 / Zhouyi v3 NPU driver
# Probes CIXH4000:00 (\_SB_.NPU0) + CIXH4010:0[012] (3 cores via SSDT override)
# Creates /dev/aipu chardev; inference via cix-noe-umd 2.0.2
#
# The module is aipu.ko, NOT armchina_npu. "armchina_npu" is the IN-TREE
# driver's name, and the defconfig deliberately leaves CONFIG_ARMCHINA_NPU
# unset so the in-tree copy cannot mask the vendor DKMS build. Naming it here
# produced "systemd-modules-load: Failed to find module 'armchina_npu'" on
# every boot (measured on an MS-R1 test board 2026-08-16) while doing nothing useful.
aipu
EOF

