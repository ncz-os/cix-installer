#!/bin/bash
# 27-cix-runtime.sh — verify Cix NPU runtime + write MNEMOS auto-detect env
#
# Updated 2026-05-27: uses cix-npu-umd 3.0.2 + cix-noe-umd 3.1.2 (SDK 26Q1),
# with LD_PRELOAD aipu_shim.so bridging r2p1 SDK ↔ r2p0 kernel ioctl ABI.
#
# This hook asserts the userspace pieces and writes /etc/nclawzero/embed.env.
set -euo pipefail

echo "[27] Cix NPU runtime contract"

# ----------------------------------------------------------------------
# 1. Verify SDK packages are installed
# ----------------------------------------------------------------------
runtime_ok=1
for pkg in cix-npu-umd cix-noe-umd; do
    status=$(dpkg-query -W -f='${Status}' "$pkg" 2>/dev/null || true)
    if [ "$status" = "install ok installed" ]; then
        version=$(dpkg-query -W -f='${Version}' "$pkg" 2>/dev/null || echo "?")
        echo "[27]   $pkg installed: $version"
    else
        echo "[27]   WARN: $pkg NOT installed"
        runtime_ok=0
    fi
done

# ----------------------------------------------------------------------
# 2. /dev/aipu sanity
# ----------------------------------------------------------------------
if [ -c /dev/aipu ]; then
    echo "[27]   /dev/aipu present"
    AIPU_PRESENT=1
else
    echo "[27]   /dev/aipu not present (normal in chroot)"
    AIPU_PRESENT=0
fi

# ----------------------------------------------------------------------
# 3. NPU shim verification
# ----------------------------------------------------------------------
SHIM=/opt/ncz/aipu_shim.so
if [ -f "$SHIM" ]; then
    echo "[27]   shim present: $SHIM"
else
    echo "[27]   shim not built yet — 47-embedkit.sh will build it"
fi

# ----------------------------------------------------------------------
# 4. GPU Vulkan verification
# ----------------------------------------------------------------------
if command -v vulkaninfo >/dev/null 2>&1; then
    GPU=$(vulkaninfo --summary 2>/dev/null | grep "Mali-G720" | head -1 || echo "not detected")
    echo "[27]   GPU: $GPU"
else
    echo "[27]   vulkan-tools not installed (16-gpu-userspace.sh handles this)"
fi

# ----------------------------------------------------------------------
# 5. CPU embeddings baseline
# ----------------------------------------------------------------------
if [ -d /opt/ncz/embed-venv ]; then
    echo "[27]   embed venv present"
    if /opt/ncz/embed-venv/bin/python3 -c "import fastembed; print('fastembed OK')" 2>/dev/null; then
        echo "[27]   fastembed import OK (CPU embeddings ready)"
    fi
fi

# ----------------------------------------------------------------------
# 6. Write embed.env
# ----------------------------------------------------------------------
install -d -m 0755 /etc/nclawzero
cat > /etc/nclawzero/embed.env << EOF
# Auto-generated by 27-cix-runtime.sh (2026-05-27)
EMBEDKIT_VENV=/opt/ncz/embed-venv
EMBEDKIT_PYTHON=/opt/ncz/embed-venv/bin/python3
EMBEDKIT_NPU_SHIM=/opt/ncz/aipu_shim.so
EMBEDKIT_MODELS_DIR=/opt/ncz/models
EMBEDKIT_DEFAULT_MODEL=bge-small-zh-v1.5
EMBEDKIT_DEFAULT_TIER=cpu-fastembed
EMBEDKIT_NPU_DRIVER_VERSION=$(dpkg-query -W -f='${Version}' cix-npu-umd 2>/dev/null || echo unknown)
EMBEDKIT_LIBNOE_VERSION=$(dpkg-query -W -f='${Version}' cix-noe-umd 2>/dev/null || echo unknown)
EOF
chmod 644 /etc/nclawzero/embed.env

echo "[27] runtime contract complete"
echo "[27]   NPU: $( [ $AIPU_PRESENT -eq 1 ] && echo "present" || echo "chroot" )"
echo "[27]   SDK: cix-npu-umd=$(dpkg-query -W -f='${Version}' cix-npu-umd 2>/dev/null || echo ?) cix-noe-umd=$(dpkg-query -W -f='${Version}' cix-noe-umd 2>/dev/null || echo ?)"
