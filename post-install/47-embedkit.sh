#!/bin/bash
# 47-embedkit.sh — MNEMOS embedding appliance for Reinhardt 26.5 / June 1
#
# Updated 2026-05-27 for the June 1 release stack:
#   - uv + managed Python 3.13 venv (Python 3.14 compat)
#   - fastembed for CPU embeddings (~200 docs/sec on Sky1)
#   - libnoe 3.1.2 + NOE_Engine for NPU path
#   - NPU: LD_PRELOAD shim bridges r2p1 SDK ↔ r2p0 kernel ioctl ABI
#   - Mali-G720 Vulkan via panvk (for future GPU compute path)
#
# Layout:
#   /opt/ncz/embed-venv/           — uv venv, Python 3.13
#   /opt/ncz/embed-venv/bin/python3
#   /opt/ncz/aipu_shim.so           — NPU ioctl translation shim
#   /opt/ncz/models/                — model files
set -euo pipefail

ASSETS=/usr/local/lib/cix-installer/assets
VENV=/opt/ncz/embed-venv
MODELS=/opt/ncz/models

echo "[47] embedkit install (uv + fastembed + NPU shim)"

# ----------------------------------------------------------------------
# 1. Install uv (if not present)
# ----------------------------------------------------------------------
if ! command -v uv >/dev/null 2>&1; then
    echo "[47]   installing uv..."
    curl -LsSf https://astral.sh/uv/install.sh | sh
    export PATH="$HOME/.local/bin:$PATH"
fi

# ----------------------------------------------------------------------
# 2. Create Python 3.13 venv with uv
# ----------------------------------------------------------------------
if [ ! -d "$VENV" ]; then
    echo "[47]   creating uv venv at $VENV with Python 3.13"
    uv python install 3.13 2>&1 | tail -2
    uv venv --python 3.13 "$VENV"
else
    echo "[47]   venv already exists at $VENV"
fi

# ----------------------------------------------------------------------
# 3. Install CPU embedding stack (fastembed)
#    fastembed is ~10x faster than llama-cpp for embeddings on Sky1 Neoverse
# ----------------------------------------------------------------------
echo "[47]   installing fastembed (CPU embeddings)"
"$VENV/bin/pip" install --quiet fastembed 2>&1 | tail -2

# ----------------------------------------------------------------------
# 4. Install libnoe (NPU userspace binding) from SDK wheel
# ----------------------------------------------------------------------
LIBNOE_WHL=/usr/share/cix/pypi/libnoe-3.1.2-py3-none-manylinux2014_aarch64.whl
if [ -f "$LIBNOE_WHL" ]; then
    echo "[47]   installing libnoe 3.1.2 (NPU binding)"
    "$VENV/bin/pip" install --quiet "$LIBNOE_WHL" 2>&1 | tail -2
else
    echo "[47]   WARN: $LIBNOE_WHL not found — NPU path disabled"
fi

# ----------------------------------------------------------------------
# 5. Build and install NPU ioctl shim
#    Bridges r2p1 SDK struct sizes ↔ r2p0 kernel struct sizes
# ----------------------------------------------------------------------
if [ -f "$ASSETS/npu-shim/aipu_shim.c" ]; then
    echo "[47]   building NPU ioctl shim"
    gcc -shared -fPIC -o "$VENV/aipu_shim.so" "$ASSETS/npu-shim/aipu_shim.c" -ldl 2>&1 | tail -2
    # Also place in /opt/ncz for easy LD_PRELOAD
    cp "$VENV/aipu_shim.so" /opt/ncz/aipu_shim.so 2>/dev/null || true
    echo "[47]   shim: /opt/ncz/aipu_shim.so"
else
    echo "[47]   WARN: no shim source — NPU ioctl translation unavailable"
fi

# ----------------------------------------------------------------------
# 6. Stage models at /opt/ncz/models/
# ----------------------------------------------------------------------
mkdir -p "$MODELS"
# NPU model (Compass NN AOT-compiled, INT8) — from ARGONAS if available
MODEL_SRC=/mnt/argonas/datapool/projects/cix-ai-model-hub/latest/models/Generative_AI/Text_Image_Search/onnx_bge_small_zh
if [ -f "$MODEL_SRC/bge-small-zh_256.cix" ]; then
    cp "$MODEL_SRC/bge-small-zh_256.cix" "$MODELS/" 2>/dev/null && \
        echo "[47]   staged bge-small-zh_256.cix (NPU model)"
fi

# ----------------------------------------------------------------------
# 7. Write embed.env for MNEMOS auto-detect
# ----------------------------------------------------------------------
mkdir -p /etc/nclawzero
cat > /etc/nclawzero/embed.env << EOF
# Generated by 47-embedkit.sh
EMBEDKIT_VENV=${VENV}
EMBEDKIT_PYTHON=${VENV}/bin/python3
EMBEDKIT_NPU_SHIM=/opt/ncz/aipu_shim.so
EMBEDKIT_MODELS_DIR=${MODELS}
EMBEDKIT_DEFAULT_MODEL=bge-small-zh-v1.5
EMBEDKIT_DEFAULT_TIER=cpu-fastembed
EMBEDKIT_NPU_DRIVER_VERSION=$(dpkg-query -W -f='${Version}' cix-npu-umd 2>/dev/null || echo unknown)
EMBEDKIT_LIBNOE_VERSION=$(dpkg-query -W -f='${Version}' cix-noe-umd 2>/dev/null || echo unknown)
EOF
chmod 644 /etc/nclawzero/embed.env

echo "[47] embedkit install complete"
echo "[47]   venv:     $VENV"
echo "[47]   models:   $MODELS ($(ls $MODELS 2>/dev/null | wc -l) files)"
echo "[47]   embed.env: /etc/nclawzero/embed.env"
