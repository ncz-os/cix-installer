#!/bin/bash
# gen-hooks-lists.sh -- generate post-install/hooks.list.<platform> from the
# platform inventory (docs/platform-inventory.tsv).
#
#   build/gen-hooks-lists.sh           write both lists
#   build/gen-hooks-lists.sh --check   fail if a list on disk differs from the
#                                      inventory (used by build/lint-platform.sh)
#
# A numbered hook post-install/NN-name.sh is listed for a platform when its
# inventory class is `common` or `mixed` (all platforms), or the platform's own
# class (`sky1` -> sky1-arm64, `amd64` -> amd64).  Order is the filename sort,
# which is the execution order run-all.sh has always used.
#
# See docs/PLATFORM-SPLIT-DESIGN.md.
set -euo pipefail

ROOT="${NCZ_LINT_ROOT:-$(git -C "$(dirname "$0")" rev-parse --show-toplevel)}"
INV="$ROOT/docs/platform-inventory.tsv"
HOOKDIR="$ROOT/post-install"
PLATFORMS="sky1-arm64 amd64"
MODE=write
[ "${1:-}" = "--check" ] && MODE=check

[ -f "$INV" ] || { echo "gen-hooks-lists: missing $INV" >&2; exit 2; }

plat_class() { case "$1" in sky1-arm64) echo sky1 ;; amd64) echo amd64 ;; esac; }

render() {  # $1 = platform
    local plat="$1" own
    own=$(plat_class "$plat")
    printf '# hooks.list.%s -- GENERATED by build/gen-hooks-lists.sh from docs/platform-inventory.tsv.\n' "$plat"
    printf '# Do not edit by hand. One hook per line, in execution order.\n'
    printf '# post-install/run-all.sh runs ONLY the hooks named here (plus 70-bootloader and 99-diagnostics via its EXIT trap).\n'
    awk -F'\t' -v own="$own" '
        /^#/ || NF < 4 { next }
        $1 ~ /^post-install\/[0-9][0-9]-[^\/]*\.sh$/ && ($2 == "common" || $2 == "mixed" || $2 == own) {
            n = $1; sub(/^post-install\//, "", n); print n
        }' "$INV" | LC_ALL=C sort
}

rc=0
for plat in $PLATFORMS; do
    out="$HOOKDIR/hooks.list.$plat"
    # After the physical split each list is a source file of its own platform.
    [ -d "$ROOT/platforms/$plat/post-install" ] && out="$ROOT/platforms/$plat/post-install/hooks.list.$plat"
    if [ "$MODE" = check ]; then
        if ! render "$plat" | diff -q "$out" - >/dev/null 2>&1; then
            echo "gen-hooks-lists: $out is out of date; run build/gen-hooks-lists.sh" >&2
            rc=1
        fi
    else
        render "$plat" > "$out"
        echo "gen-hooks-lists: wrote $out ($(grep -vc '^#' "$out") hooks)"
    fi
done
exit $rc
