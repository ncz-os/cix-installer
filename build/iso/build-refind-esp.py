#!/usr/bin/env python3
"""
build-refind-esp.py — Build a deterministic FAT ESP image carrying rEFInd and
its ISO9660 driver, with a small menu that loads the d-i kernel/initrd from
ISO9660 paths (the "preferred layout" in design §8).

Implements the small-ESP path: rEFInd + drivers + a tiny config live inside
the ESP; rEFInd reaches the installer kernel and initrd on the ISO filesystem
via the iso9660 driver. The layout is what rEFInd documents for ISO boot and
is what we attempt to qualify first per the design doc.

Layout produced:

    EFI/BOOT/BOOTX64.EFI                 (refind_x64.efi, renamed for fallback boot)
    EFI/REFIND/REFIND-X64.EFI            (refind_x64.efi under arch-named path)
    EFI/REFIND/DRIVERS/ISO9660_X64.EFI   (ISO9660 filesystem driver)
    EFI/REFIND/DRIVERS/EXT4_X64.EFI      (ext4 driver — useful for installed systems later)
    EFI/REFIND/REFIND.CONF               (explicit menu — no auto-scan reliance)

The ESP is built with mtools (mformat + mcopy): a 4 MiB flat FAT32 image,
deterministically populated from the rEFInd .deb payload.

Output: <out_dir>/esp.img  + <out_dir>/receipt.json
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def find_refind_extract(arch: str) -> Path:
    """Locate the extracted rEFInd .deb payload.

    amd64 -> prototype/work/refind-ar/refind-extract/usr/share/refind/refind
    arm64 -> prototype/work/refind-arm-ar/refind-extract/usr/share/refind/refind
    """
    if arch == "amd64":
        base = REPO_ROOT / "prototype" / "work" / "refind-ar" / "refind-extract" / "usr" / "share" / "refind" / "refind"
    elif arch == "arm64":
        base = REPO_ROOT / "prototype" / "work" / "refind-arm-ar" / "refind-extract" / "usr" / "share" / "refind" / "refind"
    else:
        raise ValueError(f"unsupported arch: {arch}")
    if not base.is_dir():
        raise FileNotFoundError(
            f"rEFInd extract not found at {base}; run extract-refind-deb.sh first"
        )
    return base


REFIND_CONF_TEXT = """\
#
# refind.conf -- generated by build/iso/build-refind-esp.py
# Every entry is explicit; we do NOT rely on rEFInd's auto-scan because
# auto-scan requires rEFInd to enumerate ISO9660 contents, and the ISO9660
# driver presence/behavior is part of what we are qualifying. The explicit
# loader/initrd paths below are the ones rEFInd will look up via the
# ISO9660 driver (EFI/REFIND/DRIVERS/).
#
# timeout 10: 10s before default boot (graphical install) if no key press.
# scanfor manual: ignore auto-scanned disks; use only the explicit entries.
# textonly: keep output compatible with serial consoles and QEMU's default
#           headless mode -- graphical banners add boot time we don't need.
#
# Paths below match the substrate-import layout for the Bookworm amd64
# netboot mini ISO (kernel + initrd at ISO root). The arm64/full-netinst
# variants live in REFIND_CONF_TEXT_ARM64.
#

timeout 10
textonly
scanfor manual

menuentry "Install (graphical)" {
    loader /linux
    initrd /initrd.gz
    options "auto=true priority=critical locale=en_US.UTF-8 keyboard-configuration/layoutcode=us DEBIAN_FRONTEND=newt"
}

menuentry "Install (expert)" {
    loader /linux
    initrd /initrd.gz
    options "priority=low DEBIAN_FRONTEND=newt"
}

menuentry "Rescue mode" {
    loader /linux
    initrd /initrd.gz
    options "rescue/enable=true DEBIAN_FRONTEND=newt"
}

menuentry "Reinstall (preserve installed system)" {
    disabled
}
"""


# arm64 (and full-netinst) variants use the /install.<arch>/ layout.
REFIND_CONF_TEXT_ARM64 = REFIND_CONF_TEXT.replace("/linux\n", "/install.arm/vmlinuz\n").replace(
    "/initrd.gz", "/install.arm/initrd.gz"
)


# amd64 full-netinst (different ISO) — kept for completeness.
REFIND_CONF_TEXT_AMD64_FULL = REFIND_CONF_TEXT.replace("/linux\n", "/install.amd/vmlinuz\n").replace(
    "/initrd.gz", "/install.amd/initrd.gz"
)


# OVMF's startup.nsh. When the firmware boots the EFI Internal Shell from
# the OVMF volume, it auto-runs startup.nsh if found on the boot device.
# We put one in EFI/BOOT/ so OVMF reads it and launches rEFInd. This
# also makes the image qualify under a stricter firmware that does not
# present "EFI Internal Shell" as the default — rEFInd's own loader will
# take over once it runs.
STARTUP_NSH = """\\
@echo -off
\\EFI\\BOOT\\BOOTX64.EFI
\\EFI\\BOOT\\BOOTAA64.EFI
"""


def build_esp_dir(esp_root: Path, refind_src: Path, arch: str) -> None:
    """Materialize the EFI/ tree inside esp_root/. Deterministic ordering."""
    if esp_root.exists():
        shutil.rmtree(esp_root)
    esp_root.mkdir(parents=True)

    if arch == "amd64":
        efi_arch = "x64"
        boot_loader = "BOOTX64.EFI"
        refind_loader = "REFIND-X64.EFI"
        iso_driver = "ISO9660_X64.EFI"
        ext4_driver = "EXT4_X64.EFI"
        driver_dir = "drivers_x64"
        conf_text = REFIND_CONF_TEXT
    else:  # arm64
        efi_arch = "aa64"
        boot_loader = "BOOTAA64.EFI"
        refind_loader = "REFIND-AA64.EFI"
        iso_driver = "ISO9660_AA64.EFI"
        ext4_driver = "EXT4_AA64.EFI"
        driver_dir = "drivers_aa64"
        conf_text = REFIND_CONF_TEXT_ARM64

    # Locate source files in the extracted .deb
    refind_efi_src = refind_src / f"refind_{efi_arch}.efi"
    iso_driver_src = refind_src / driver_dir / f"iso9660_{efi_arch}.efi"
    ext4_driver_src = refind_src / driver_dir / f"ext4_{efi_arch}.efi"

    if not refind_efi_src.is_file():
        raise FileNotFoundError(f"missing rEFInd EFI binary: {refind_efi_src}")
    if not iso_driver_src.is_file():
        raise FileNotFoundError(f"missing rEFInd ISO9660 driver: {iso_driver_src}")

    boot_dir = esp_root / "EFI" / "BOOT"
    boot_dir.mkdir(parents=True)
    shutil.copy2(str(refind_efi_src), str(boot_dir / boot_loader))

    refind_dir = esp_root / "EFI" / "REFIND"
    refind_dir.mkdir()
    shutil.copy2(str(refind_efi_src), str(refind_dir / refind_loader))

    drivers_dir = refind_dir / "DRIVERS"
    drivers_dir.mkdir()
    shutil.copy2(str(iso_driver_src), str(drivers_dir / iso_driver))
    if ext4_driver_src.is_file():
        shutil.copy2(str(ext4_driver_src), str(drivers_dir / ext4_driver))

    # Place the rEFInd config
    (refind_dir / "REFIND.CONF").write_text(conf_text)

    # Place startup.nsh in EFI/BOOT so OVMF's "EFI Internal Shell" launches
    # rEFInd on first boot (a strict firmware without rEFInd written into
    # NVRAM boot entries needs an explicit launch).
    (boot_dir / "startup.nsh").write_text(STARTUP_NSH)

    # mcopy copies modes 0644 by default but we chmod anyway for determinism.
    for root, dirs, files in os.walk(esp_root):
        for d in dirs:
            os.chmod(Path(root) / d, 0o755)
        for f in files:
            os.chmod(Path(root) / f, 0o644)


def make_fat_image_mtools(esp_root: Path, out_img: Path, size_mib: int = 4) -> dict:
    """Build a FAT32 image using mtools (mformat + mcopy). mtools is the
    portable, deterministic path: it writes a flat file directly and supports
    8.3 only (which is fine for our small file set).

    The ``-i`` option is required on macOS (and accepted everywhere) to
    point mtools at a flat image file instead of a drive letter."""
    mformat = shutil.which("mformat")
    mcopy = shutil.which("mcopy")
    mmd = shutil.which("mmd")
    if not (mformat and mcopy and mmd):
        raise RuntimeError("mtools (mformat/mcopy/mmd) is required on PATH")

    out_img.parent.mkdir(parents=True, exist_ok=True)
    if out_img.exists():
        out_img.unlink()

    # Create the flat image file
    with out_img.open("wb") as f:
        f.truncate(size_mib * 1024 * 1024)

    # Format with FAT32 (-F) and a fixed-volume label. mformat derives the
    # geometry from the file size (FAT32, sectors/track 63, heads 16 by
    # default for the "small image" geometry it picks). We pin a numeric
    # serial (4 bytes) so the formatted image is reproducible.
    serial = "0x4bcd8d9c"
    subprocess.run([
        mformat,
        "-i", str(out_img),   # image file (replaces the positional device arg)
        "-F",                 # force FAT32 even on tiny images
        "-v", "REFIND",       # volume label
        "-N", serial,         # serial number (stable)
    ], check=True)

    # Recursive copy. mtools' -s flag preserves modes but does NOT
    # auto-create parent directories. Walk the source tree and copy file
    # by file, creating each parent directory with mmd. We pin the file
    # copy order (sorted by path) so the image is reproducible.
    for src_file in sorted(esp_root.rglob("*")):
        if not src_file.is_file():
            continue
        rel = src_file.relative_to(esp_root).as_posix()
        # Build the parent directory path with leading slash.
        parent_parts = src_file.relative_to(esp_root).parent.parts
        # Create each parent directory level if missing.
        cur = ""
        for part in parent_parts:
            cur = f"{cur}/{part}"
            # mmd is idempotent on existing dirs; ignore "already exists".
            subprocess.run([mmd, "-i", str(out_img), f"::{cur}"],
                           check=False, capture_output=True)
        subprocess.run([
            mcopy, "-i", str(out_img), "-pQ",
            str(src_file), f"::{rel}",
        ], check=True)

    return {
        "tool": "mtools",
        "tool_version": subprocess.check_output(["mformat", "-V"], text=True).strip(),
        "image": str(out_img),
        "size_bytes": out_img.stat().st_size,
        "serial": serial,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--arch", required=True, choices=["amd64", "arm64"])
    ap.add_argument("--out-dir", required=True, type=Path)
    ap.add_argument("--size-mib", type=int, default=4,
                    help="ESP image size in MiB (default 4)")
    ap.add_argument("--keep-tree", action="store_true",
                    help="keep the intermediate EFI/ tree on disk")
    args = ap.parse_args()

    refind_src = find_refind_extract(args.arch)
    esp_root = args.out_dir / "esp-tree"
    build_esp_dir(esp_root, refind_src, args.arch)

    esp_img = args.out_dir / "esp.img"
    info = make_fat_image_mtools(esp_root, esp_img, args.size_mib)

    esp_img_sha = sha256_file(esp_img)
    esp_img_size = esp_img.stat().st_size

    if arch := args.arch:
        refind_efi_path = refind_src / ("refind_x64.efi" if arch == "amd64" else "refind_aa64.efi")
        iso_driver_path = refind_src / ("drivers_x64/iso9660_x64.efi" if arch == "amd64" else "drivers_aa64/iso9660_aa64.efi")

    receipt = {
        "schema_version": "esp-receipt/v1",
        "arch": args.arch,
        "esp_image": str(esp_img.relative_to(args.out_dir)),
        "esp_image_sha256": esp_img_sha,
        "esp_image_size_bytes": esp_img_size,
        "build_tool": info,
        "refind_efi_sha256": sha256_file(refind_efi_path),
        "iso9660_driver_sha256": sha256_file(iso_driver_path),
        "esp_tree_inventory": sorted(
            str(p.relative_to(esp_root)) for p in esp_root.rglob("*") if p.is_file()
        ),
    }
    (args.out_dir / "receipt.json").write_text(json.dumps(receipt, indent=2, sort_keys=True))
    print(f"ESP image: {esp_img}")
    print(f"  sha256:  {esp_img_sha}")
    print(f"  size:    {esp_img_size} bytes ({esp_img_size / 1024 / 1024:.2f} MiB)")
    print(f"  build:   {info['tool']} ({info.get('tool_version', '')})")

    if not args.keep_tree:
        shutil.rmtree(esp_root)
    return 0


if __name__ == "__main__":
    sys.exit(main())