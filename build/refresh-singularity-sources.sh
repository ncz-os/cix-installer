#!/bin/bash
# refresh-singularity-sources.sh -- resolve the Singularity desktop payload
# source pins for one image build (the `refresh-sources` stage of
# build/build-image.sh).
#
# DESIGN RULE (2026-10-10): "I want latest singularity, latest build
# sources."  This tool resolves the LATEST upstream sources for the payload and
# freezes them into a receipt so a build is reproducible from recorded pins.
#
#   --sources latest   resolve the current upstream HEAD of the superproject and
#                      of every tracked-branch submodule (via
#                      build/singularity-pins.sh propose), plus the labwc meson
#                      wraps for the compositor chain (SceneFX / wlroots /
#                      libsfdo), and the latest compatible upstream HEAD of
#                      SceneFX (main) and wlroots (the 0.20 branch).
#   --sources pinned   use the committed assets/singularity/upstream-pins.tsv
#                      unchanged (reproduces an old build).
#
# Outputs (in --output DIR) -- the "receipt": every resolved commit SHA.
#   upstream-pins.tsv        singularity-pins.sh-format superproject+submodule pins
#   compositor-pins.tsv      path<TAB>component<TAB>url<TAB>revision<TAB>resolved_sha<TAB>note
#   source-resolution.json   all SHAs + a manifest sha256 (determinism = these pins)
#
# It does NOT build anything and does NOT overwrite the committed pins (a
# `latest` resolution is frozen into the run dir, never committed implicitly).
# The payload build (build/build-singularity.sh) consumes upstream-pins.tsv via
# NCZ_SINGULARITY_PINS and applies the SceneFX libmali patch.
#
# Usage:
#   build/refresh-singularity-sources.sh --sources latest|pinned \
#       --output DIR [--arch amd64|arm64] [--pins FILE] [--offline] [--dry-run]
set -uo pipefail

HERE="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"

SOURCES=""; OUTPUT=""; ARCH=""; PINS="${NCZ_SINGULARITY_PINS:-$ROOT/assets/singularity/upstream-pins.tsv}"
OFFLINE=0; DRY_RUN=0
while [ $# -gt 0 ]; do
  case "$1" in
    --sources) SOURCES="${2:?}"; shift 2 ;;
    --output)  OUTPUT="${2:?}"; shift 2 ;;
    --arch)    ARCH="${2:?}"; shift 2 ;;
    --pins)    PINS="${2:?}"; shift 2 ;;
    --offline) OFFLINE=1; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    -h|--help) sed -n '2,45p' "$0"; exit 0 ;;
    *) echo "refresh-singularity-sources: unknown argument: $1" >&2; exit 2 ;;
  esac
done
case "$SOURCES" in latest|pinned) ;; *) echo "refresh-singularity-sources: --sources latest|pinned is required" >&2; exit 2 ;; esac
[ -n "$OUTPUT" ] || { echo "refresh-singularity-sources: --output DIR is required" >&2; exit 2; }

die() { echo "refresh-singularity-sources: ERROR: $*" >&2; exit 1; }
command -v git >/dev/null || die "git not found"
command -v python3 >/dev/null || die "python3 not found"
PINTOOL="$ROOT/build/singularity-pins.sh"
[ -x "$PINTOOL" ] || die "missing $PINTOOL"

mkdir -p "$OUTPUT"
UP="$OUTPUT/upstream-pins.tsv"
COMP="$OUTPUT/compositor-pins.tsv"
RES="$OUTPUT/source-resolution.json"
: > "$COMP"

# ---------------------------------------------------------------------------
# 1. resolve the superproject + submodule pins
# ---------------------------------------------------------------------------
if [ "$SOURCES" = pinned ]; then
  [ -r "$PINS" ] || die "--sources pinned but $PINS is unreadable"
  cp -f "$PINS" "$UP"
  echo "[sources] pinned: copied committed pins from $(basename "$PINS")"
else
  echo "[sources] latest: resolving upstream heads via singularity-pins.sh propose"
  if [ "$DRY_RUN" = 1 ]; then
    echo "[sources] dry-run: not resolving (would call: singularity-pins.sh propose)"
    exit 0
  fi
  [ "$OFFLINE" = 1 ] && die "--offline cannot resolve 'latest' (needs the network)"
  tmp="$(mktemp "${TMPDIR:-/tmp}/ncz-sing-propose.XXXXXX")" || die "mktemp failed"
  trap 'rm -f "$tmp"' EXIT
  NCZ_SINGULARITY_PINS="$PINS" bash "$PINTOOL" propose > "$tmp" || die "singularity-pins.sh propose failed"
  [ -s "$tmp" ] || die "propose produced no rows"
  {
    printf '# Singularity Desktop upstream source pins -- RESOLVED LATEST at build time.\n'
    printf '# Generated by build/refresh-singularity-sources.sh --sources latest; frozen for\n'
    printf '# this run and recorded (with the deb sha256) in the build receipt.  NOT committed\n'
    printf '# implicitly: a deliberate bump is reviewed, check-patched, rebuilt, then committed.\n'
    printf '# Columns: path<TAB>url<TAB>branch<TAB>sha (see assets/singularity/upstream-pins.tsv)\n'
    cat "$tmp"
  } > "$UP"
  echo "[sources] latest: froze $(grep -vcE '^[#[:space:]]*$' "$tmp") rows into $(basename "$UP")"
  rm -f "$tmp"; trap - EXIT
fi

# Sanity: validate the frozen file through the real reader.
NCZ_SINGULARITY_PINS="$UP" bash "$PINTOOL" validate >/dev/null 2>&1 \
  || die "the resolved upstream-pins.tsv does not validate (see: singularity-pins.sh validate)"

# ---------------------------------------------------------------------------
# 2. compositor chain -- labwc's meson wraps (SceneFX / wlroots / libsfdo)
# ---------------------------------------------------------------------------
# SceneFX is labwc's meson [wrap-git] subproject, not a superproject submodule,
# so singularity-pins.sh cannot see it.  Resolve the wraps from the pinned labwc
# commit and, for a `latest` build, also the latest compatible upstream HEAD of
# SceneFX (main) and wlroots (the 0.20 branch; master is 0.21-dev and labwc +
# SceneFX both require <0.21.0 -- see the resolver report).
LABWC_SHA="$(awk -F'\t' '$1=="subprojects/labwc"{print $4; exit}' "$UP")"
LABWC_URL="$(awk -F'\t' '$1=="subprojects/labwc"{print $2; exit}' "$UP")"
echo "[sources] labwc pin: ${LABWC_SHA:-<none>}"

wrap_field() { awk -F'=' -v k="$2" '{key=$1; gsub(/^[ \t]+|[ \t]+$/,"",key)} key==k{v=$2; gsub(/^[ \t]+|[ \t]+$/,"",v); print v; exit}' "$1"; }

# Clone labwc at its pin (shallow) to read the wraps.  Uses the pin cache when
# present; otherwise the network.
REPO_CACHE="${NCZ_SINGULARITY_PIN_CACHE:-$ROOT/build/.singularity-pin-cache}"
WRAP_WORK="$(mktemp -d "${TMPDIR:-/tmp}/ncz-wraps.XXXXXX")" || die "mktemp failed"
trap 'rm -rf "$WRAP_WORK"' EXIT
resolve_wrap() { # resolve_wrap <wrap-name> <component> <ref>
  local name="$1" comp="$2" ref="$3" wrap="$WRAP_WORK/labwc/subprojects/$1.wrap" url rev sha
  [ -f "$wrap" ] || { echo "[sources] note: no $name.wrap in labwc $LABWC_SHA"; return 0; }
  url="$(wrap_field "$wrap" url)"; rev="$(wrap_field "$wrap" revision)"
  [ -n "$url" ] || { echo "[sources] note: $name.wrap has no url"; return 0; }
  [ -n "$ref" ] || ref="$rev"
  sha="$(git ls-remote "$url" "$ref" 2>/dev/null | awk '{print $1; exit}')"
  if [ -z "$sha" ]; then
    # maybe a raw sha or a tag
    case "$ref" in
      [0-9a-f][0-9a-f]*) sha="$ref" ;;
      *) sha="$(git ls-remote --tags "$url" "refs/tags/$ref" 2>/dev/null | awk '{print $1; exit}')" ;;
    esac
  fi
  [ -n "$sha" ] || sha="UNRESOLVED"
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "subprojects/labwc/subprojects/$1" "$comp" "$url" "$rev" "$sha" "wrap revision (labwc $LABWC_SHA)" >> "$COMP"
  echo "[sources] compositor $comp: wrap rev=$rev resolved=$sha"
}

if [ -n "$LABWC_SHA" ] && [ "$DRY_RUN" != 1 ]; then
  git init -q "$WRAP_WORK/labwc" 2>/dev/null
  git -C "$WRAP_WORK/labwc" remote add origin "$LABWC_URL" 2>/dev/null || true
  if git -C "$WRAP_WORK/labwc" fetch -q --depth 1 "$LABWC_URL" "$LABWC_SHA" 2>/dev/null \
     || git -C "$WRAP_WORK/labwc" fetch -q "$LABWC_URL" "$LABWC_SHA" 2>/dev/null; then
    git -C "$WRAP_WORK/labwc" checkout -q --detach FETCH_HEAD 2>/dev/null || true
    resolve_wrap scenefx "SceneFX" ""
    resolve_wrap wlroots "wlroots" ""
    resolve_wrap libsfdo "libsfdo" ""
  else
    echo "[sources] WARN: could not fetch labwc $LABWC_SHA to read the wraps" >&2
  fi
fi

# latest compatible upstream compositor HEADs (recorded; the build uses the
# labwc wrap set unless compositor-pins.tsv carries an explicit override row).
if [ "$SOURCES" = latest ] && [ "$DRY_RUN" != 1 ]; then
  for spec in \
      "SceneFX|https://github.com/wlrfx/scenefx.git|refs/heads/main" \
      "wlroots|https://gitlab.freedesktop.org/wlroots/wlroots.git|refs/heads/0.20"; do
    comp="${spec%%|*}"; rest="${spec#*|}"; url="${rest%%|*}"; ref="${rest#*|}"
    sha="$(git ls-remote "$url" "$ref" 2>/dev/null | awk '{print $1; exit}')"
    [ -n "$sha" ] || sha="UNRESOLVED"
    printf '%s\t%s\t%s\t%s\t%s\t%s\n' "latest" "$comp" "$url" "$ref" "$sha" "latest compatible upstream HEAD" >> "$COMP"
    echo "[sources] latest upstream $comp ($ref): $sha"
  done
fi
trap - EXIT; rm -rf "$WRAP_WORK"

# ---------------------------------------------------------------------------
# 3. receipt
# ---------------------------------------------------------------------------
python3 -I - "$UP" "$COMP" "$RES" "$SOURCES" "${ARCH:-}" "$ROOT" <<'PYEOF'
import hashlib, json, sys, time
up, comp, res, sources, arch, root = sys.argv[1:7]
def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()
repos = []
with open(up) as f:
    for ln in f:
        ln = ln.rstrip("\n")
        if not ln or ln.startswith("#"):
            continue
        parts = ln.split("\t")
        if len(parts) >= 4:
            repos.append({"path": parts[0], "url": parts[1], "branch": parts[2], "sha": parts[3]})
compositors = []
import os
if os.path.exists(comp):
    with open(comp) as f:
        for ln in f:
            ln = ln.rstrip("\n")
            if not ln:
                continue
            p = ln.split("\t")
            if len(p) >= 5:
                compositors.append({"path": p[0], "component": p[1], "url": p[2],
                                    "revision": p[3], "resolved_sha": p[4],
                                    "note": p[5] if len(p) > 5 else ""})
doc = {
    "schema": "ncz-singularity-source-resolution/v1",
    "sources": sources,
    "arch": arch,
    "resolved_at": int(time.time()),
    "upstream_pins_sha256": sha256(up),
    "compositor_pins_sha256": sha256(comp) if os.path.exists(comp) else None,
    "repos": repos,
    "compositors": compositors,
    "n_repos": len(repos),
}
# manifest digest over the pins (determinism = these pins)
m = hashlib.sha256()
m.update(doc["upstream_pins_sha256"].encode())
if doc["compositor_pins_sha256"]:
    m.update(doc["compositor_pins_sha256"].encode())
doc["pins_manifest_sha256"] = m.hexdigest()
with open(res, "w") as fh:
    json.dump(doc, fh, indent=2, sort_keys=True); fh.write("\n")
print(f"[sources] wrote {res}: {len(repos)} repos, {len(compositors)} compositor rows, manifest {doc['pins_manifest_sha256'][:16]}")
PYEOF

echo "[sources] done: $SOURCES -> $OUTPUT"
