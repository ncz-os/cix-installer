#!/bin/bash
# test-t2-native-packages.sh -- targeted tests for the T2 native-NCZ package
# acquisition function (post-install/55-t2-firmware.sh's ncz_t2_apt_acquire),
# which replaces the old "fetch t2-ubuntu-repo KEY.gpg + write t2.list +
# apt-get install from the Ubuntu vendor repo" path.
#
# The contract:
#   * simulate first (apt-get install -s ...); rc != 0 OR any "Remv " line
#     refuses the install and never runs the real install;
#   * sim and real install use the SAME expanded args array (including -y and
#     --no-install-recommends); no force / allow-downgrades / trust waiver;
#   * real install failure (apt-get exit != 0) is honestly propagated;
#   * dpkg-query -W verifies each package really landed (post-install rc=0
#     but dpkg disagrees is also a failure -- "apt exited ok" is not enough);
#   * applies to BOTH the main A/B packages and the dmg2img helper, same
#     function, same discipline.
#
# The test sources ONLY the small `ncz_t2_apt_acquire` block (marker
# t2-acquire-fn) from the hook -- it does NOT execute the whole hook on the
# Mac/live host, so it's safe to run anywhere.
#
# Run: bash build/test-t2-native-packages.sh     Exit 0 = pass, 1 = fail.
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${NCZ_TEST_ROOT:-$(cd "$HERE/.." && pwd)}"
HOOK="$ROOT/post-install/55-t2-firmware.sh"
W="$(mktemp -d -t t2-acquire.XXXXXX)"; trap 'rm -rf "$W"' EXIT
PASS=0; FAIL=0
ok()  { echo "  PASS  $1"; PASS=$((PASS + 1)); return 0; }
bad() { echo "  FAIL  $1"; FAIL=$((FAIL + 1)); [ -n "${2:-}" ] && printf '%s\n' "$2" | sed 's/^/        /'; return 0; }

# --- syntax + marker-block extraction --------------------------------------
bash -n "$HOOK" && ok "55-t2-firmware.sh parses" || bad "55-t2-firmware.sh syntax"
FNBLOCK="$W/fn.sh"
sed -n '/^# BEGIN t2-acquire-fn$/,/^# END t2-acquire-fn$/p' "$HOOK" \
    | sed '1d;$d' > "$FNBLOCK"
[ -s "$FNBLOCK" ] && ok "t2-acquire-fn marker block extracted" \
    || { bad "marker block missing"; exit 1; }

# --- mocks ------------------------------------------------------------------
# apt-get behavior is controlled by the SCENARIO env var; the same script
# produces every outcome the contract cares about.
mkdir -p "$W/bin"
cat > "$W/bin/apt-get" <<'EOF'
#!/bin/sh
echo "apt-get $*" >> "$LOG"
case " $* " in
    *" update "*) exit 0 ;;
    *" -s "*)
        # simulation output
        case "$SCENARIO" in
            ok)    echo "Inst apple-firmware-script apple-t2-audio-config" ;;
            remv)  echo "Inst apple-firmware-script"; echo "Remv alsa-ucm-conf [1]" ;;
            simfail) echo "E: Unable to locate package apple-firmware-script" >&2 ;;
        esac
        case "$SCENARIO" in
            simfail) exit 100 ;;
            *)       exit 0 ;;
        esac
        ;;
    *" install "*)
        case "$SCENARIO" in
            ok)      exit 0 ;;
            instfail) exit 100 ;;
            remv|simfail) echo "REAL_INSTALL_RAN_EVEN_THOUGH_SIM_SAID_REMOVE" >&2; exit 99 ;;
            *)       exit 0 ;;
        esac
        ;;
esac
EOF
# dpkg-query: reports each package in $INSTALLED as installed; otherwise exit 1
# (so the Status string is empty -> the function returns 5 honestly).
cat > "$W/bin/dpkg-query" <<'EOF'
#!/bin/sh
for a in "$@"; do p="$a"; done
case " ${INSTALLED:-} " in *" $p "*) printf 'install ok installed'; exit 0 ;; esac
exit 1
EOF
chmod +x "$W/bin/"*
export PATH="$W/bin:$PATH"
LOG="$W/apt.log"
export LOG

# --- run helper: source the function block and call it once ----------------
mkroot() { rm -rf "$W/r" "$LOG" "$W/out"; mkdir -p "$W/r"; : > "$LOG"; : > "$W/out"; }
# run_acquire captures BOTH the function's stdout (ncz_t2_log "..." echoes)
# and its stderr to $W/out so the test can assert on the real captured
# diagnostic output, not on $LOG (which only records apt-get calls).
run_acquire() {   # <pkgs...>  (uses $SCENARIO, $INSTALLED, $LOG)
    ( . "$FNBLOCK"
      ncz_t2_apt_acquire "$@"
    ) > "$W/out" 2>&1
    return $?
}

# --- contract: hook does NOT add/trust the t2-ubuntu-repo anymore -----------
echo "=== source: no t2-ubuntu-repo wiring, no Intel-openvino wiring ==="
grep -q 'adityagarg8.github.io/t2-ubuntu-repo\|t2-ubuntu-repo' "$HOOK" && grep -q 'cat > /etc/apt/sources.list.d/t2.list' "$HOOK" \
    && bad "hook still wires t2-ubuntu-repo sources.list" \
    || ok "hook no longer writes /etc/apt/sources.list.d/t2.list"
grep -q 'curl.*t2-ubuntu-repo/KEY.gpg' "$HOOK" && bad "hook still fetches t2-ubuntu-repo KEY.gpg" \
    || ok "hook no longer fetches t2-ubuntu-repo KEY.gpg"
grep -q 'apt.repos.intel.com\|ubuntu24' "$HOOK" && bad "hook references the Intel OpenVINO ubuntu24 repo" \
    || ok "hook does not reference apt.repos.intel.com / ubuntu24"
# Legacy entry, when found on an upgraded install, is moved aside (renamed
# to .disabled-for-build) -- NOT removed, NOT generated by us.
grep -q '\.disabled-for-build' "$HOOK" && ok "legacy t2.list disable path is reversible (.disabled-for-build)" \
    || bad "legacy t2.list is removed globally instead of moved aside"

# --- case A: clean simulate, real install succeeds, all installed --------
echo "=== case A: clean sim + real install + dpkg agrees -> rc=0 ==="
mkroot; SCENARIO=ok INSTALLED="apple-firmware-script apple-t2-audio-config" run_acquire apple-firmware-script apple-t2-audio-config
rc=$?
[ "$rc" = 0 ] && ok "rc=0 on the happy path" || bad "rc=$rc on happy path" "$(cat "$LOG")"
# Same-args parity: the sim and the real install must have used the SAME
# expanded arg shape (both include -y and --no-install-recommends, and both
# receive the same package list).
_sim_args=$(grep 'apt-get install -s' "$LOG" | head -1)
_real_args=$(grep 'apt-get install -y' "$LOG" | head -1)
# Strip the leading "apt-get " so we compare the args the install call got.
_sim_stripped=${_sim_args#apt-get install -s }
_real_stripped=${_real_args#apt-get install }
[ "$_sim_stripped" = "$_real_stripped" ] \
    && ok "sim and real install use the SAME expanded args ($_sim_stripped)" \
    || bad "sim/real args differ: sim=[$_sim_stripped] real=[$_real_stripped]"
# No force / allow-downgrades / trust waiver may be in the args.
grep -q 'force-yes\|allow-downgrades\|AllowUnauthenticated' "$LOG" \
    && bad "real install used a force / allow-downgrades / trust waiver" \
    || ok "real install has no force / allow-downgrades / trust waiver"

# --- case B: sim says Remv -> real install must NOT run ------------------
echo "=== case B: sim reports Remv -> real install is NOT run, rc=2 ==="
mkroot; SCENARIO=remv INSTALLED="apple-firmware-script apple-t2-audio-config" run_acquire apple-firmware-script apple-t2-audio-config
rc=$?
[ "$rc" = 2 ] && ok "rc=2 when sim says Remv" || bad "rc=$rc (want 2) on Remv" "$(cat "$LOG")"
grep -q 'apt-get install -y' "$LOG" \
    && bad "real install RAN despite sim saying Remv" \
    || ok "real install did NOT run when sim said Remv"

# --- case C: sim fails (rc != 0) -> real install must NOT run -----------
echo "=== case C: sim fails (rc=100) -> real install is NOT run, rc=2 ==="
mkroot; SCENARIO=simfail run_acquire apple-firmware-script apple-t2-audio-config
rc=$?
[ "$rc" = 2 ] && ok "rc=2 when sim itself fails" || bad "rc=$rc (want 2) on simfail" "$(cat "$LOG")"
grep -q 'apt-get install -y' "$LOG" \
    && bad "real install RAN despite sim failing" \
    || ok "real install did NOT run when sim failed"

# --- case D: real install fails (rc != 0) -> rc=4, status honest --------
echo "=== case D: real install fails (rc=100) -> rc=4, status is honest ==="
mkroot; SCENARIO=instfail INSTALLED="" run_acquire apple-firmware-script apple-t2-audio-config
rc=$?
[ "$rc" = 4 ] && ok "rc=4 on real install failure" || bad "rc=$rc (want 4) on instfail" "$(cat "$LOG")"
# In this case, the status check AFTER the install failure should NOT have
# claimed success; the function returns 4 before doing the dpkg-query loop,
# so this verifies the failure is the last word.
grep -q 'post-install status:.* not installed' "$LOG" \
    && bad "post-install status check ran despite install failure" \
    || ok "post-install status check did NOT run after install failure"

# --- case E: real install claims success but dpkg disagrees -> rc=5 ---
echo "=== case E: install rc=0 but dpkg disagrees -> rc=5 (honest status) ==="
mkroot; SCENARIO=ok INSTALLED="" run_acquire apple-firmware-script apple-t2-audio-config
rc=$?
[ "$rc" = 5 ] && ok "rc=5 when apt-get says ok but dpkg disagrees" || bad "rc=$rc (want 5) when dpkg disagrees" "$(cat "$LOG")"
# The WARN comes from ncz_t2_log, which echoes to the function's stdout; the
# test captures function output to $W/out (ncz_t2_log is NOT routed through
# the apt-get mock so $LOG cannot see it). grep against the captured output.
grep -q 'post-install status: apple-firmware-script not installed' "$W/out" \
    && ok "post-install status check honestly reports the missing package" \
    || bad "post-install status check missing the WARN" "out=$(cat "$W/out") log=$(cat "$LOG")"

# --- case F: same discipline applies to dmg2img --------------------------
echo "=== case F: dmg2img uses the same function (same args, sim/real parity) ==="
mkroot; SCENARIO=ok INSTALLED="dmg2img" run_acquire dmg2img
rc=$?
[ "$rc" = 0 ] && ok "dmg2img rc=0 on happy path" || bad "dmg2img rc=$rc on happy path" "$(cat "$LOG")"
_sim_args=$(grep 'apt-get install -s' "$LOG" | head -1)
_real_args=$(grep 'apt-get install -y' "$LOG" | head -1)
_sim_stripped=${_sim_args#apt-get install -s }
_real_stripped=${_real_args#apt-get install }
[ "$_sim_stripped" = "$_real_stripped" ] \
    && ok "dmg2img: sim and real install use the SAME expanded args ($_sim_stripped)" \
    || bad "dmg2img: sim/real args differ"
mkroot; SCENARIO=remv INSTALLED="dmg2img" run_acquire dmg2img
rc=$?
[ "$rc" = 2 ] && grep -q 'apt-get install -y' "$LOG" \
    && bad "dmg2img: real install RAN despite sim saying Remv" \
    || ok "dmg2img: real install did NOT run when sim said Remv"

# --- real temporary-file fixtures of ncz_t2_disable_legacy_vendor_list -------
echo "=== fixture: ncz_t2_disable_legacy_vendor_list on real temp files ==="
# Extract the function from the hook (not behind a marker block) and source
# it; then drive it with REAL files (not grep) to verify the URI-parsing
# fix, the comment-only migration, the unique-backup discipline, and the
# idempotent second run.
sed -n '/^ncz_t2_disable_legacy_vendor_list() {/,/^}$/p' "$HOOK" > "$W/disabler.sh"
[ -s "$W/disabler.sh" ] && ok "disabler function extracted from hook" \
    || { bad "disabler function missing from hook"; exit 1; }

# (a) Real legacy t2.list with bracket options BEFORE the URL -- the parser
# must skip `[signed-by=...]` and recognize the legacy adityagarg8 host.
# The file is rewritten in place (comment-only migration); the original
# bytes are preserved in a unique .disabled-for-build.XXXXXX backup.
_a="$W/d/legacy-t2"; mkdir -p "$(dirname "$_a")"
cat > "$_a" <<'TLIST'
# legacy t2.list shipped by old installer
deb [signed-by=/usr/share/keyrings/t2-ubuntu-repo-KEY.gpg] http://adityagarg8.github.io/t2-ubuntu-repo/deb generic main
TLIST
_orig_bytes=$(cat "$_a")
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$_a" ) > "$W/out" 2>&1
[ -f "$_a" ] \
    && ok "legacy t2.list is rewritten in place (not renamed away)" \
    || bad "legacy t2.list was renamed away instead of rewritten" "$(cat "$W/out")"
# The legacy deb line must now be commented out.
grep -q '^#.*adityagarg8.github.io/t2-ubuntu-repo' "$_a" \
    && ok "legacy deb line is commented out in place" \
    || bad "legacy deb line was not commented out" "$(cat "$_a")"
# The original comment line must be preserved verbatim.
grep -q '^# legacy t2.list shipped by old installer$' "$_a" \
    && ok "unrelated comment line preserved verbatim" \
    || bad "unrelated comment line was lost" "$(cat "$_a")"
# A unique backup must exist and be byte-identical to the original.
_bak=$(ls "$_a".disabled-for-build.* 2>/dev/null | head -1)
[ -n "$_bak" ] && [ -f "$_bak" ] \
    && ok "unique .disabled-for-build.XXXXXX backup created" \
    || bad "no unique backup created" "$(ls -la "$W/d")"
[ "$(cat "$_bak")" = "$_orig_bytes" ] \
    && ok "backup bytes are byte-identical to the original" \
    || bad "backup bytes differ from the original"
# Second run must be idempotent: no new backup, no further change.
_bak_count_before=$(ls "$_a".disabled-for-build.* 2>/dev/null | wc -l)
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$_a" ) > "$W/out" 2>&1
_bak_count_after=$(ls "$_a".disabled-for-build.* 2>/dev/null | wc -l)
[ "$_bak_count_before" = "$_bak_count_after" ] \
    && ok "second run is idempotent (no new backup)" \
    || bad "second run created an extra backup"

# (b) Unrelated deb line (Debian trixie mirror) -- must be left alone.
_b="$W/d/mirror"; mkdir -p "$(dirname "$_b")"
cat > "$_b" <<'MLIST'
deb http://deb.debian.org/debian trixie main
MLIST
_b_orig=$(cat "$_b")
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$_b" ) > "$W/out" 2>&1
[ -f "$_b" ] && [ "$(cat "$_b")" = "$_b_orig" ] \
    && ok "unrelated Debian mirror line is left alone (operator content preserved)" \
    || bad "unrelated mirror line was incorrectly modified"
[ -z "$(ls "$_b".disabled-for-build.* 2>/dev/null)" ] \
    && ok "no backup created for an unrelated file" \
    || bad "unrelated file got a backup"

# (c) Mixed file: FIRST unrelated Debian row, SECOND signed-by vendor row.
# Only the vendor row must be commented; the Debian row must remain ACTIVE.
_c="$W/d/mixed"; mkdir -p "$(dirname "$_c")"
cat > "$_c" <<'XLIST'
# user note: don't touch unrelated entries below
deb http://deb.debian.org/debian trixie main
deb [signed-by=/usr/share/keyrings/t2-ubuntu-repo-KEY.gpg] http://adityagarg8.github.io/t2-ubuntu-repo/deb generic main
# user-added unrelated comment / kept verbatim
XLIST
_c_orig=$(cat "$_c")
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$_c" ) > "$W/out" 2>&1
[ -f "$_c" ] \
    && ok "mixed file is rewritten in place" \
    || bad "mixed file was renamed away"
grep -q '^deb http://deb.debian.org/debian trixie main$' "$_c" \
    && ok "unrelated Debian row remains ACTIVE" \
    || bad "unrelated Debian row was commented or removed" "$(cat "$_c")"
grep -q '^#.*adityagarg8.github.io/t2-ubuntu-repo' "$_c" \
    && ok "vendor row is commented out" \
    || bad "vendor row was not commented" "$(cat "$_c")"
grep -q '^# user-added unrelated comment / kept verbatim$' "$_c" \
    && ok "unrelated user comment preserved verbatim" \
    || bad "unrelated user comment was lost"
_c_bak=$(ls "$_c".disabled-for-build.* 2>/dev/null | head -1)
[ -n "$_c_bak" ] && [ "$(cat "$_c_bak")" = "$_c_orig" ] \
    && ok "mixed-file backup is byte-identical to the original" \
    || bad "mixed-file backup differs from the original"

# (c2) Reversed order: FIRST signed-by vendor row, SECOND unrelated Debian row.
_c2="$W/d/mixed-rev"; mkdir -p "$(dirname "$_c2")"
cat > "$_c2" <<'XLIST2'
deb [signed-by=/usr/share/keyrings/t2-ubuntu-repo-KEY.gpg] http://adityagarg8.github.io/t2-ubuntu-repo/deb generic main
deb http://deb.debian.org/debian trixie main
XLIST2
_c2_orig=$(cat "$_c2")
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$_c2" ) > "$W/out" 2>&1
grep -q '^#.*adityagarg8.github.io/t2-ubuntu-repo' "$_c2" \
    && ok "reversed order: vendor row commented" \
    || bad "reversed order: vendor row not commented" "$(cat "$_c2")"
grep -q '^deb http://deb.debian.org/debian trixie main$' "$_c2" \
    && ok "reversed order: unrelated Debian row remains ACTIVE" \
    || bad "reversed order: unrelated Debian row was modified" "$(cat "$_c2")"
_c2_bak=$(ls "$_c2".disabled-for-build.* 2>/dev/null | head -1)
[ -n "$_c2_bak" ] && [ "$(cat "$_c2_bak")" = "$_c2_orig" ] \
    && ok "reversed order: backup byte-identical to original" \
    || bad "reversed order: backup differs from original"

# (d) Already-disabled file (ending in .disabled-for-build) -- must be
# skipped, never re-processed (no piling-up of suffixes).
_d="$_bak"
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$_d" ) > "$W/out" 2>&1
[ -f "$_d" ] && [ ! -f "$_d.disabled-for-build" ] \
    && ok "already-disabled backup file is skipped (no pile-up of suffixes)" \
    || bad "already-disabled file was re-processed"

# (e) Existing backup must NOT be overwritten or deleted. Create a
# pre-existing backup with distinct bytes, run the disabler, and verify
# the pre-existing backup is unchanged.
_e="$W/d/clash1"; _existing="$W/d/clash1.disabled-for-build"
mkdir -p "$(dirname "$_e")"
printf 'pre-existing operator backup (do NOT overwrite)\n' > "$_existing"
_existing_before=$(cat "$_existing")
cat > "$_e" <<'ELIST'
deb [signed-by=/usr/share/keyrings/t2-ubuntu-repo-KEY.gpg] http://adityagarg8.github.io/t2-ubuntu-repo/deb generic main
ELIST
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$_e" ) > "$W/out" 2>&1
[ "$(cat "$_existing")" = "$_existing_before" ] \
    && ok "pre-existing backup was NOT overwritten or deleted" \
    || bad "pre-existing backup was overwritten"
# A NEW unique backup must have been created alongside the pre-existing one.
_new_bak=$(ls "$_e".disabled-for-build.* 2>/dev/null | head -1)
[ -n "$_new_bak" ] && [ "$_new_bak" != "$_existing" ] \
    && ok "a new unique backup was created alongside the pre-existing one" \
    || bad "no new unique backup created"

# (f) mv-failure fixture: if the atomic replace fails, the original must be
# preserved and the function must return non-zero. Simulate by making the
# parent directory read-only after the temp file is created -- but since
# mktemp needs write access, instead we test the symlink refusal path
# (which is the practical failure mode we can trigger without root).
_f="$W/d/symlink-target"; mkdir -p "$(dirname "$_f")"
printf 'deb http://adityagarg8.github.io/t2-ubuntu-repo/deb generic main\n' > "$_f"
_f_orig=$(cat "$_f")
ln -sf "$_f" "$W/d/symlink-link"
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$W/d/symlink-link" ) > "$W/out" 2>&1
_rc=$?
[ "$_rc" != 0 ] \
    && ok "symlink refusal returns non-zero" \
    || bad "symlink refusal returned zero"
[ "$(cat "$_f")" = "$_f_orig" ] \
    && ok "symlink target preserved on refusal" \
    || bad "symlink target was modified"

# (g) Intel fixture: same comment-only migration + unique backup discipline.
# Extract the Intel disabler and drive it with real temp files.
INTEL_LIB="$ROOT/post-install/lib/intel-accel.sh"
sed -n '/^ncz_intel_disable_legacy_vendor_list() {/,/^}$/p' "$INTEL_LIB" > "$W/intel-disabler.sh"
[ -s "$W/intel-disabler.sh" ] && ok "intel disabler function extracted" \
    || bad "intel disabler function missing"
# Provide the helper the Intel disabler calls.
cat > "$W/intel-helpers.sh" <<'HELPEOF'
ncz_intel_log() { echo "[intel-accel] $*"; }
ncz_intel_log_err() { echo "[intel-accel] $*" >&2; }
HELPEOF
_ia="$W/d/intel-legacy"; mkdir -p "$(dirname "$_ia")"
cat > "$_ia" <<'ILIST'
# legacy intel-openvino.list shipped by an older installer
deb http://deb.debian.org/debian trixie main
deb [signed-by=/usr/share/keyrings/intel-openvino.gpg] https://apt.repos.intel.com/openvino/2024/ubuntu noble main
ILIST
_ia_orig=$(cat "$_ia")
( . "$W/intel-helpers.sh"; . "$W/intel-disabler.sh"; ncz_intel_disable_legacy_vendor_list "$_ia" ) > "$W/out" 2>&1
[ -f "$_ia" ] \
    && ok "intel: file rewritten in place" \
    || bad "intel: file was renamed away"
grep -q '^deb http://deb.debian.org/debian trixie main$' "$_ia" \
    && ok "intel: unrelated Debian row remains ACTIVE" \
    || bad "intel: unrelated Debian row was modified" "$(cat "$_ia")"
grep -q '^#.*apt.repos.intel.com' "$_ia" \
    && ok "intel: vendor row commented out" \
    || bad "intel: vendor row not commented" "$(cat "$_ia")"
_ia_bak=$(ls "$_ia".disabled-for-build.* 2>/dev/null | head -1)
[ -n "$_ia_bak" ] && [ "$(cat "$_ia_bak")" = "$_ia_orig" ] \
    && ok "intel: backup byte-identical to original" \
    || bad "intel: backup differs from original"
# Idempotent second run.
_ia_bak_count_before=$(ls "$_ia".disabled-for-build.* 2>/dev/null | wc -l)
( . "$W/intel-helpers.sh"; . "$W/intel-disabler.sh"; ncz_intel_disable_legacy_vendor_list "$_ia" ) > "$W/out" 2>&1
_ia_bak_count_after=$(ls "$_ia".disabled-for-build.* 2>/dev/null | wc -l)
[ "$_ia_bak_count_before" = "$_ia_bak_count_after" ] \
    && ok "intel: second run is idempotent" \
    || bad "intel: second run created an extra backup"

# --- contract: existing T2 boot-noise / staged firmware / BT checks intact
echo "=== existing T2 behaviour contracts (preserved) ==="
grep -q 'feature_disable=0x10' "$HOOK"              && ok "brcmfmac P2P disable (0x10) still present" || bad "brcmfmac P2P disable missing"
grep -q 'ncz-t2-brcmfmac-p2p.conf' "$HOOK"          && ok "modprobe.d/ncz-t2-brcmfmac-p2p.conf still written" || bad "brcmfmac p2p modprobe.d missing"
grep -q 'ncz-t2-pcspkr.conf' "$HOOK"                && ok "modprobe.d/ncz-t2-pcspkr.conf still written" || bad "pcspkr modprobe.d missing"
grep -q 'blacklist snd_pcsp' "$HOOK"                && ok "snd_pcsp still blacklisted" || bad "snd_pcsp blacklist missing"
grep -q 'ncz-t2-hid-sensor-rotation.conf' "$HOOK"   && ok "modprobe.d/ncz-t2-hid-sensor-rotation.conf still written" || bad "hid_sensor_rotation modprobe.d missing"
grep -q 'blacklist hid_sensor_rotation' "$HOOK"     && ok "hid_sensor_rotation still blacklisted" || bad "hid_sensor_rotation blacklist missing"
grep -q 'install hid_sensor_rotation /bin/true' "$HOOK" && ok "hid_sensor_rotation install override still in place" || bad "hid_sensor_rotation install override missing"
grep -q 'T2_BT_FW_MODELS' "$HOOK"                   && ok "chip-class BT firmware verification preserved" || bad "BT firmware verification missing"
grep -q 'BCM4377-class' "$HOOK"                     && ok "BCM4377 branch preserved" || bad "BCM4377 branch missing"
grep -q 'brcm/BCM.hcd is intentionally absent' "$HOOK" && ok "expected-absent BCM.hcd reporting preserved" || bad "BCM.hcd expected-absent reporting missing"
grep -q 'apple-t2-firmware-sonoma14.tar.xz' "$HOOK" && ok "staged firmware asset path preserved" || bad "staged firmware asset path missing"
grep -q 'get-apple-firmware get_from_online' "$HOOK" && ok "online get-apple-firmware fallback preserved" || bad "online fallback missing"
grep -q 'echo 7 | get-apple-firmware get_from_online' "$HOOK" \
                                          && ok "Sonoma (option 7) pinned input preserved" \
                                          || bad "Sonoma input pin missing"
# Stage runs BEFORE the apt step so a missing native package never skips it.
# Verify the staged-extraction call precedes the apt-acquire call. The
# actual staged call is `ncz_t2_extract_staged_firmware || STAGED_FW_RC=$?`,
# so match the call prefix, not the bare function name.
_stage=$(grep -nE '^ncz_t2_extract_staged_firmware[[:space:]]*\|\|' "$HOOK" | head -1 | cut -d: -f1)
_acquire=$(grep -n 'ncz_t2_apt_acquire apple-firmware-script' "$HOOK" | head -1 | cut -d: -f1)
[ -n "$_stage" ] && [ -n "$_acquire" ] && [ "$_stage" -lt "$_acquire" ] \
    && ok "staged firmware extraction runs BEFORE native package acquire (no early-exit before stage)" \
    || bad "staged firmware is NOT before the apt acquire call (stage=$_stage acquire=$_acquire)"
# apt update is best-effort inside the function: pipe through `tail` so a
# network-only failure does NOT propagate a non-zero exit before the staging
# path runs. No `Acquire::Check-Date=false` -- that would be an unrelated
# metadata date-check bypass.
grep -q 'apt-get update 2>&1 | tail -5' "$HOOK" \
    && ok "apt-get update inside the function is best-effort (no -e fatal)" \
    || bad "apt-get update may be fatal in the function"
# The date-bypass string must only appear in a NEGATIVE comment (explaining
# why it is NOT set), never in an executable line. Strip comment-only lines
# before grepping so the explanatory comment does not trip the ban.
if grep -vE '^[[:space:]]*#' "$HOOK" | grep -q 'Acquire::Check-Date=false'; then
    bad "hook sets Acquire::Check-Date=false in executable code (unsolicited metadata date-check bypass)"
else
    ok "no Acquire::Check-Date date-check bypass in executable code"
fi
# Hook does not exit before staged firmware is attempted on a key/repo miss.
grep -q '^exit 0' "$HOOK" && grep -q 'could not fetch.*t2-ubuntu-repo KEY' "$HOOK" \
    && bad "hook still early-exits when the old key fetch fails (before stage)" \
    || ok "hook has no early-exit on key fetch failure"
# Hook exits 1 (preserved contract for build/test-hooks-fail-loudly.sh).
grep -q 'T2_PKG_FAIL" = 1' "$HOOK" && grep -q 'exit 1' "$HOOK" \
    && ok "hook exits 1 when T2_PKG_FAIL is set (existing contract)" \
    || bad "hook does not exit 1 on T2_PKG_FAIL"
# Staged-extraction failure returns 2 (distinct from missing=1) and blocks
# the success path. Verify the function body distinguishes the two.
grep -q 'return 2' "$HOOK" && grep -q 'return 1' "$HOOK" \
    && ok "staged extraction distinguishes missing (1) from tar failure (2)" \
    || bad "staged extraction does not distinguish missing from tar failure"
# The post-install status block must gate on >= 2, not != 0 && != 1.
grep -q 'STAGED_FW_RC" -ge 2' "$HOOK" \
    && ok "post-install status gates on STAGED_FW_RC >= 2 (hard failure)" \
    || bad "post-install status does not gate on STAGED_FW_RC >= 2"

# === fixture: ncz_t2_extract_staged_firmware return codes ===
# Extract the actual function from the HOOK and run it under shell functions
# that shadow mkdir and tar so no live /lib writes occur. Verify return
# codes: 0 on success, 1 when tarball missing, 2 when tar fails.

sed -n '/^ncz_t2_extract_staged_firmware() {/,/^}$/p' "$HOOK" > "$W/t2stage.sh"
[ -s "$W/t2stage.sh" ] && ok "ncz_t2_extract_staged_firmware extracted from HOOK" \
    || { bad "ncz_t2_extract_staged_firmware missing from HOOK"; exit 1; }

# (a) success path: tarball exists as regular file, tar returns 0.
_t2a="$W/t2/success.tar.xz"
mkdir -p "$(dirname "$_t2a")"
printf 'fake tarball bytes\n' > "$_t2a"
( . "$W/t2stage.sh"; STAGED_FW_TARBALL="$_t2a"; mkdir() { :; }; tar() { return 0; }; ncz_t2_extract_staged_firmware ) > "$W/out" 2>&1
_rc=$?
[ "$_rc" -eq 0 ] && ok "T2 stage success returns 0" \
    || bad "T2 stage success returned $_rc (expected 0)" "$(cat "$W/out")"

# (b) missing tarball: returns 1.
_t2b="$W/t2/missing.tar.xz"
rm -f "$_t2b"
( . "$W/t2stage.sh"; STAGED_FW_TARBALL="$_t2b"; mkdir() { :; }; tar() { return 0; }; ncz_t2_extract_staged_firmware ) > "$W/out" 2>&1
_rc=$?
[ "$_rc" -eq 1 ] && ok "T2 stage missing tarball returns 1" \
    || bad "T2 stage missing tarball returned $_rc (expected 1)" "$(cat "$W/out")"

# (c) tar failure: returns 2.
_t2c="$W/t2/corrupt.tar.xz"
printf 'not really a tarball\n' > "$_t2c"
( . "$W/t2stage.sh"; STAGED_FW_TARBALL="$_t2c"; mkdir() { :; }; tar() { return "$TAR_RC"; }; TAR_RC=1; ncz_t2_extract_staged_firmware ) > "$W/out" 2>&1
_rc=$?
[ "$_rc" -eq 2 ] && ok "T2 stage tar failure returns 2" \
    || bad "T2 stage tar failure returned $_rc (expected 2)" "$(cat "$W/out")"

# (d) legacy lookalike host fixture unchanged using already-extracted disabler.
_t2d="$W/r/etc/apt/sources.list.d/t2-lookalike.list"
mkdir -p "$(dirname "$_t2d")"
printf 'deb https://adityagarg8.github.io.example.invalid/t2-ubuntu-repo ./\n' > "$_t2d"
_t2d_before=$(cat "$_t2d")
( . "$W/disabler.sh"; ncz_t2_disable_legacy_vendor_list "$_t2d" ) > "$W/out" 2>&1
_rc=$?
[ "$_rc" = 0 ] && [ "$(cat "$_t2d")" = "$_t2d_before" ] \
    && ok "T2 disabler preserves an unrelated lookalike host" \
    || bad "T2 disabler changed an unrelated lookalike host" "$(cat "$W/out")"


echo "=== accepted native A/B versions and failed legacy migration ==="
_native_specs=$(sed -n 's/^[[:space:]]*ncz_t2_apt_acquire \(apple-firmware-script=.*\)$/\1/p' "$HOOK")
if [ "$_native_specs" = 'apple-firmware-script=20261015+ncz1 apple-t2-audio-config=0.5.1+ncz1' ]; then
    ok "main transaction requires the actual accepted native package versions"
else
    bad "main native package versions differ from accepted artifacts" "$_native_specs"
fi
read -r -a _native_args <<< "$_native_specs"
mkroot; SCENARIO=ok INSTALLED="apple-firmware-script apple-t2-audio-config" run_acquire "${_native_args[@]}"
_rc=$?
[ "$_rc" = 0 ] && grep -Fq "apt-get install -y --no-install-recommends $_native_specs" "$LOG" \
    && ok "exact native versions reach APT while dpkg status checks use package names" \
    || bad "exact-version acquisition failed" "$(cat "$W/out")"
mkroot; SCENARIO=simfail INSTALLED="apple-firmware-script apple-t2-audio-config" run_acquire "${_native_args[@]}"
_rc=$?
[ "$_rc" = 2 ] && ! grep -q 'apt-get install -y' "$LOG" \
    && ok "old installed names cannot mask an unavailable exact native transaction" \
    || bad "failed native transaction was accepted with old installed names"
mkroot; T2_LEGACY_FAIL=1 SCENARIO=ok INSTALLED=dmg2img run_acquire dmg2img
_rc=$?
[ "$_rc" = 2 ] && [ ! -s "$LOG" ] \
    && ok "legacy migration failure prevents every APT call, including dmg2img fallback" \
    || bad "APT ran after a failed legacy migration" "$(cat "$LOG")"

echo "---"
echo "t2-native-packages tests: $PASS passed, $FAIL failed"
